for letter,sheet in sheets.items():
    parts=['<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">',
           '<rect width="1024" height="1024" fill="#F7F5EF"/>',
           '<style>text{font-family:system-ui,sans-serif;fill:#263B37}.slot{fill:#edf1ea;stroke:#477C78;stroke-width:1}.safe{fill:none;stroke:#CB5635;stroke-width:1;stroke-dasharray:5 4}</style>']
    for a in sheet['assets']:
        x,y,w,h,s=a['x'],a['y'],a['width'],a['height'],a['safeInset']
        small=w<200
        parts.append(f'<rect class="slot" x="{x}" y="{y}" width="{w}" height="{h}"/>')
        parts.append(f'<rect class="safe" x="{x+s}" y="{y+s}" width="{w-2*s}" height="{h-2*s}"/>')
        cx,cy=x+w/2,y+h/2
        lines=[f"{a['id']} · {a['name']}",f"x{x} y{y} · {w}×{h}",f"安全内边 {s}px"]
        for i,line in enumerate(lines):
            parts.append(f'<text x="{cx}" y="{cy+(i-1)*(14 if small else 30)}" text-anchor="middle" font-size="{8 if small else 20}">{escape(line)}</text>')
    parts.append('</svg>')
    (out/f'layout-{letter.lower()}.svg').write_text('\n'.join(parts)+'\n')

